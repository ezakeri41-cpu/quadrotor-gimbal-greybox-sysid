function [A,B,C,D,K,x0] = yawODE(a1,a0,b,Tm,Ts,outSel,useLag)
%YAWODE  Grey-box structure of the gimbal yaw axis.
%
%   States (useLag = false):  x = [psi ; psi_dot]
%       psi_ddot = -a1*psi_dot - a0*psi + b*u
%
%   States (useLag = true):   x = [psi ; psi_dot ; tau]
%       psi_ddot = -a1*psi_dot - a0*psi + tau
%       tau_dot  = (-tau + b*u)/Tm          (ESC + rotor spin-up lag)
%
%   u   : NORMALIZED yaw torque command (tau_z_cmd, dimensionless)
%   a1  = c/Iz     [1/s]     bearing friction + rotor drag damping
%   a0  = k/Iz     [1/s^2]   weak torsional stiffness (wiring harness / cables)
%   b   = ku/Iz    [rad/s^2] control effectiveness, ku = physical N*m per unit command
%   Tm  [s]        actuator (ESC+rotor) time constant
%
%   outSel : 'yaw' | 'rate' | 'both'
%
%   DIFFERENCES FROM THE ROLL/PITCH AXES:
%
%   1) There is NO gravity restoring torque about the vertical axis, so the
%      textbook model psi_ddot = tau_z/Iz is structurally much closer to the
%      truth here than it was for roll/pitch. The small a0 that does come out
%      of the fit is torsional stiffness of the wiring harness, not a pendulum.
%      Its natural frequency (~0.15 Hz) sits BELOW the excited chirp band
%      (0.3-2 Hz), so a0 is only weakly identifiable - treat it with caution
%      and do not over-interpret its value.
%
%   2) Yaw torque is generated by rotor DRAG, not by thrust differential, so
%      it is several times weaker than roll/pitch. Expect b ~ 7 rather than
%      the 25 (roll) / 43 (pitch) seen on the other axes.
%
%   3) The actuator lag Tm is not identifiable from this data (the optimizer
%      drives it to ~0). USE_LAG = false is the sensible default for yaw.

if useLag
    A  = [ 0     1     0
          -a0   -a1    1
           0     0   -1/Tm ];
    B  = [0; 0; b/Tm];
else
    A  = [ 0     1
          -a0   -a1 ];
    B  = [0; b];
end

n  = size(A,1);
x0 = zeros(n,1);

switch lower(outSel)
    case 'yaw'
        C = [1 zeros(1,n-1)];
    case 'rate'
        C = [0 1 zeros(1,n-2)];
    case 'both'
        C = [eye(2) zeros(2,n-2)];
    otherwise
        error('outSel must be ''yaw'', ''rate'' or ''both''.');
end

D = zeros(size(C,1),1);
K = zeros(n,size(C,1));     % output-error structure (no noise model)
end
